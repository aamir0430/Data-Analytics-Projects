SELECT
    TABLE_SCHEMA,
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE
       COLUMN_NAME LIKE '%Region%'
    OR COLUMN_NAME LIKE '%Territory%'
    OR COLUMN_NAME LIKE '%Country%'
    OR COLUMN_NAME LIKE '%State%'
    OR COLUMN_NAME LIKE '%Province%'
    OR COLUMN_NAME LIKE '%City%'
    OR COLUMN_NAME LIKE '%Location%'
    OR COLUMN_NAME LIKE '%Department%'
    OR COLUMN_NAME LIKE '%Employee%'
    OR COLUMN_NAME LIKE '%Vendor%'
ORDER BY
    TABLE_SCHEMA,
    TABLE_NAME,
    ORDINAL_POSITION;