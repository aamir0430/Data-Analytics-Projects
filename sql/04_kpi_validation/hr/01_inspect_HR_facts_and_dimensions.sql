SELECT
    TABLE_SCHEMA,
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE,
    IS_NULLABLE,
    ORDINAL_POSITION
FROM INFORMATION_SCHEMA.COLUMNS
WHERE
    TABLE_NAME LIKE '%Employee%'
    OR TABLE_NAME LIKE '%Department%'
    OR TABLE_NAME LIKE '%Shift%'
    OR TABLE_NAME LIKE '%PayHistory%'
ORDER BY
    TABLE_SCHEMA,
    TABLE_NAME,
    ORDINAL_POSITION;
